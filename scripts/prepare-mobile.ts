import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { hash, emptyCatalog, kinds, planImport } from '../src/catalog.ts';
import { validatePack } from '../src/validation.ts';
import type { ContentPack, ContentEntity, Word, Passage } from '../src/types.ts';
import type { BundleIndex } from '../mobile/engine.ts';
import { gunzipSync } from 'node:zlib';
import { splitPack } from '../src/split.ts';

const root = 'mobile/assets';
await mkdir(join(root, 'packs'), { recursive: true });
// Commit one compressed source; regenerate all native assets from it on every build.
const masterText = gunzipSync(await readFile('data/vocabulary.json.gz')).toString('utf8');
const master: ContentPack = JSON.parse(masterText);
await writeFile('data/vocabulary.json', masterText);
const index: BundleIndex = { catalog: emptyCatalog(), words: [], questions: [] };
index.notices = [];
for (const name of await readdir('data/notices')) if (/license/i.test(name)) index.notices.push({ title: name, text: await readFile(join('data/notices', name), 'utf8') });
const registry: string[] = [];
for (const pack of splitPack(master, 'vocab:initial')) {
  validatePack(pack);
  const digest = hash(pack);
  const assetName = `${digest}.pack`;
  await writeFile(join(root, 'packs', assetName), JSON.stringify(pack));
  registry.push(`  '${digest}.json': require('./packs/${assetName}'),`);
  index.catalog.packs[pack.packId] = { version: pack.packVersion, versions: { [pack.packVersion]: digest } };
  for (const kind of kinds) for (const entity of (pack[kind] ?? []) as ContentEntity[]) {
    index.catalog.entities[kind][entity.id] = { [entity.revision]: { revision: entity.revision, hash: hash(entity), file: digest + '.json',
      ...('sourceIds' in entity ? { sourceIds: entity.sourceIds } : {}),
      ...(kind === 'vocabulary' ? { senseIds: (entity as Word).senses.map(s => s.id) } : {}),
      ...(kind === 'passages' ? { paragraphIds: (entity as Passage).paragraphs.map(p => p.id) } : {}),
    } };
  }
  index.words.push(...(pack.vocabulary ?? []).map(w => ({ id: w.id, headword: w.headword, tags: w.tags, ready: w.senses.filter(s => s.status === 'ready').map(s => s.id) })));
}
const starter: ContentPack = JSON.parse(await readFile('data/starter.pack.json', 'utf8'));
// The shards are a distribution of the exact master. Register its identity too,
// so updates authored against vocabulary.json work without reinstalling that 86 MB file.
for (const kind of kinds) {
  const entities = (master[kind] ?? []) as ContentEntity[];
  if (entities.length !== Object.keys(index.catalog.entities[kind]).length) throw new Error('Shards do not match the master entity count');
  for (const entity of entities) if (index.catalog.entities[kind][entity.id]?.[entity.revision]?.hash !== hash(entity)) throw new Error(`Shard mismatch: ${entity.id}`);
}
index.catalog.packs[master.packId] = { version: master.packVersion, versions: { [master.packVersion]: hash(master) } };
const imported = planImport(index.catalog, starter);
index.catalog = imported.catalog;
await writeFile(join(root, 'packs', imported.digest + '.pack'), JSON.stringify(starter));
registry.push(`  '${imported.digest}.json': require('./packs/${imported.digest}.pack'),`);
index.words.push(...(starter.vocabulary ?? []).map(w => ({ id: w.id, headword: w.headword, tags: w.tags, ready: w.senses.filter(s => s.status === 'ready').map(s => s.id) })));
index.questions.push(...(starter.questions ?? []).map(q => ({ id: q.id, title: q.title, type: q.type, tags: q.tags })));
// Sort once on the build machine, not every time a phone opens the app.
const collator = new Intl.Collator('en');
index.words.sort((a, b) => Number(b.ready.length > 0) - Number(a.ready.length > 0) || collator.compare(a.headword, b.headword));
index.wordsSorted = true;
const wordCount = index.words.length;
const shards: string[] = [];
for (let offset = 0; offset < wordCount; offset += 2000) {
  const words = index.words.slice(offset, offset + 2000);
  const vocabulary = Object.fromEntries(words.map(w => [w.id, index.catalog.entities.vocabulary[w.id]]));
  const name = `index-${shards.length}.pack`;
  const text = JSON.stringify({ words, vocabulary });
  if (Buffer.byteLength(text) > 2 * 1024 * 1024) throw new Error('Index shard exceeds the native memory budget');
  await writeFile(join(root, name), text);
  shards.push(`require('./${name}')`);
}
index.words = [];
index.catalog.entities.vocabulary = {};
await writeFile(join(root, 'library.pack'), JSON.stringify(index));
await writeFile(join(root, 'registry.ts'), `// Generated by npm run prepare:mobile. All assets ship inside the native app.\nexport const libraryAsset = require('./library.pack');\nexport const libraryShards: number[] = [${shards.join(',\n')}];\nexport const packAssets: Record<string, number> = {\n${registry.join('\n')}\n};\n`);
console.log(JSON.stringify({ words: wordCount, questions: index.questions.length, packages: registry.length, indexShards: shards.length }));
